import { expect, test, type Page } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import type { forecastPreview } from '../../src/lib/forecast'

async function openDefinition(page: Page) {
  await page.goto('/create')
  await page.getByLabel('Question', { exact: true }).fill('What is the 24-hour BTC-USD change?')
  await page.getByLabel('Observation source', { exact: true }).fill('BTC-USD hourly opening prices, UTC')
  await page.getByLabel('Ranges', { exact: true }).fill('5')
  await page.getByLabel('Range width (%)', { exact: true }).fill('2')
}

test('range layout modes preserve independent drafts and recover from invalid boundaries', async ({ page }) => {
  const failures: string[] = []
  page.on('pageerror', error => failures.push(error.message))
  await openDefinition(page)
  const simple = page.getByRole('button', { name: 'Simple', exact: true })
  const advanced = page.getByRole('button', { name: 'Advanced', exact: true })
  const download = page.getByRole('button', { name: 'Download definition', exact: true })
  const width = page.getByLabel('Range width (%)', { exact: true })
  const price = page.getByLabel('Price per position (ETH)', { exact: true })
  const boundary = (index: number) => page.getByLabel(`Range ${index} upper (%)`, { exact: true })
  const boundaries = page.locator('.range-card input[data-edge="upper"]')
  await expect(simple).toHaveAttribute('aria-pressed', 'true')
  await width.fill('')
  await advanced.click()
  await expect(advanced).toHaveAttribute('aria-pressed', 'true')
  await expect(boundaries).toHaveCount(4)
  expect(await boundaries.evaluateAll(inputs => inputs.map(input => (input as HTMLInputElement).value))).toEqual(['-3', '-1', '1', '3'])
  await boundary(1).fill('-4.25')
  await boundary(2).fill('-0.75')
  await simple.click()
  await expect(width).toHaveValue('')
  await expect(download).toBeDisabled()
  await page.getByLabel('Ranges', { exact: true }).fill('7')
  await width.fill('1')
  await price.fill('0.000009')
  await expect(page.locator('label', { hasText: 'Price per position (ETH)' }).getByRole('alert')).toHaveText('Set at least 0.00001 ETH per position.')
  await expect(price).toHaveAttribute('aria-invalid', 'true')
  await price.fill('0.003')
  await advanced.click()
  await expect(boundaries).toHaveCount(4)
  await expect(boundary(1)).toHaveValue('-4.25')
  await expect(boundary(2)).toHaveValue('-0.75')
  await expect(price).toHaveValue('0.003')
  await boundary(2).fill('')
  await expect(download).toBeDisabled()
  await expect(page.locator('form').getByRole('alert')).toBeVisible()
  await simple.click()
  await expect(page.getByLabel('Ranges', { exact: true })).toHaveValue('7')
  await expect(width).toHaveValue('1')
  await expect(download).toBeEnabled()
  await advanced.click()
  await expect(boundary(2)).toHaveValue('')
  await expect(download).toBeDisabled()
  for (const value of ['-', '-.', '-4.25', '-0.75001']) {
    await boundary(2).fill(value)
    await expect(boundary(2)).toHaveValue(value)
    await expect(download).toBeDisabled()
    await expect(page.locator('form').getByRole('alert')).toBeVisible()
  }
  await boundary(2).fill('-0.75')
  await expect(download).toBeEnabled()
  await page.getByRole('button', { name: 'Add boundary', exact: true }).click()
  await expect(boundaries).toHaveCount(5)
  await boundary(5).fill('6')
  await expect(download).toBeEnabled()
  await page.getByRole('button', { name: 'Remove boundary 5', exact: true }).click()
  await expect(boundaries).toHaveCount(4)
  await page.getByRole('button', { name: 'Remove boundary 3', exact: true }).click()
  await expect(boundaries).toHaveCount(3)
  await expect(boundary(3)).toHaveValue('3')
  await expect(download).toBeEnabled()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  expect(failures).toEqual([])
})

test('unequal range definitions preserve exact intervals and position allocations in JSON and SIPmath', async ({ page, request }) => {
  await openDefinition(page)
  await page.getByRole('button', { name: 'Advanced', exact: true }).click()
  await page.getByLabel('Range 1 upper (%)', { exact: true }).fill('-4.25')
  await page.getByLabel('Range 2 upper (%)', { exact: true }).fill('-0.75')
  await page.getByRole('button', { name: 'Remove boundary 3', exact: true }).click()
  const diagram = page.getByRole('figure', { name: 'Range visualization' })
  const geometry = await diagram.locator('rect').evaluateAll(rects => rects.map(rect => ({ x: Number(rect.getAttribute('x')), width: Number(rect.getAttribute('width')) })))
  expect(geometry).toHaveLength(2)
  expect(geometry[0].x).toBeCloseTo(1000 / 12, 12)
  expect(geometry[0].width / geometry[1].width).toBeCloseTo(3.5 / 3.75, 12)
  expect(geometry[0].width + geometry[1].width).toBeCloseTo(1000 / 1.2, 12)
  const firstBar = diagram.getByRole('button', { name: 'Range 2: -4.25% to < -0.75%', exact: true })
  const secondBar = diagram.getByRole('button', { name: 'Range 3: -0.75% to < +3%', exact: true })
  await firstBar.click()
  await secondBar.hover()
  await expect(firstBar).toBeFocused()
  await expect(firstBar).toHaveCSS('outline-style', 'none')
  await expect(firstBar).toHaveAttribute('aria-pressed', 'false')
  await expect(secondBar).toHaveAttribute('aria-pressed', 'true')
  await expect(diagram.locator('title')).toHaveCount(0)
  await page.keyboard.press('Tab')
  await expect(secondBar).toBeFocused()
  await expect(secondBar).toHaveCSS('outline-style', 'none')
  await expect(secondBar).toHaveCSS('stroke', 'rgb(42, 35, 66)')
  await diagram.getByRole('button', { name: 'Range 2: -4.25% to < -0.75%', exact: true }).focus()
  await expect(diagram.locator('figcaption')).toHaveText('Range 2: -4.25% to < -0.75%')
  await diagram.getByRole('button', { name: 'Range 4: ≥ +3%', exact: true }).click()
  await expect(diagram.locator('figcaption')).toHaveText('Range 4: ≥ +3% | Overflow')
  await page.getByLabel('Range 2 upper (%)', { exact: true }).fill('')
  await expect(diagram.getByText('Last valid ranges', { exact: true })).toBeVisible()
  await expect(diagram.locator('rect')).toHaveCount(2)
  await page.getByLabel('Range 2 upper (%)', { exact: true }).fill('-0.75')
  await expect(diagram.getByText('Last valid ranges', { exact: true })).toHaveCount(0)
  await page.getByText('View ranges', { exact: true }).click()
  const expectedRanges = [
    { tierId: 1, lower: null, upper: -4.25, label: '< -4.25%' },
    { tierId: 2, lower: -4.25, upper: -0.75, label: '-4.25% to < -0.75%' },
    { tierId: 3, lower: -0.75, upper: 3, label: '-0.75% to < +3%' },
    { tierId: 4, lower: 3, upper: null, label: '≥ +3%' },
  ]
  const rows = page.getByRole('table').locator('tbody tr')
  await expect(rows).toHaveCount(4)
  for (const [index, range] of expectedRanges.entries()) await expect(rows.nth(index)).toContainText(range.label)
  const event = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download definition', exact: true }).click()
  const download = await event
  expect(download.suggestedFilename()).toBe('metalog-market.json')
  const definition = JSON.parse(await readFile((await download.path())!, 'utf8'))
  expect(definition.rangeBoundaries).toEqual([-4.25, -0.75, 3])
  expect(definition).not.toHaveProperty('rangeCount')
  expect(definition).not.toHaveProperty('rangeWidth')
  const input = { market: definition, coefficients: [0, 1], positions: 100 }
  const response = await request.post('/api/preview', { data: input })
  expect(response.status()).toBe(200)
  const native: ReturnType<typeof forecastPreview> = await response.json()
  expect(native.market).toEqual(definition)
  expect(native.ranges).toEqual(expectedRanges)
  expect(native.allocation.tierIds).toEqual([1, 2, 3, 4])
  expect(native.allocation.quantities).toEqual([1, 31, 63, 5])
  expect(native.payment.valueWei).toBe('100000000000000000')
  const sipmath = await request.post('/api/preview?format=sipmath', { data: input })
  expect(sipmath.status()).toBe(200)
  const library = await sipmath.json()
  expect(library.metadata.audit).toEqual(native)
  expect(library.metadata.source.market).toEqual(definition)
  expect(library.sips[1].metadata.ranges).toEqual(expectedRanges)
  expect(library.sips[1].arguments.value).toEqual([[.01, 1], [.32, 2], [.95, 3], [1, 4]])
  const invalid = await request.post('/api/preview', { data: { ...input, market: { ...definition, rangeBoundaries: [-4.25, -4.25, 3] } } })
  expect(invalid.status()).toBe(400)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})

test('optional oracle is canonical in definitions and preserves editable text across layouts', async ({ page, request }) => {
  await openDefinition(page)
  const delegate = page.getByLabel('Oracle', { exact: true })
  const download = page.getByRole('button', { name: 'Download definition', exact: true })
  const create = page.getByRole('button', { name: 'Connect to create', exact: true })
  const simple = page.getByRole('button', { name: 'Simple', exact: true })
  const advanced = page.getByRole('button', { name: 'Advanced', exact: true })
  async function definition() {
    const event = page.waitForEvent('download')
    await download.click()
    const file = await event
    return JSON.parse(await readFile((await file.path())!, 'utf8'))
  }
  await expect(delegate).toHaveValue('')
  await expect(delegate).not.toHaveAttribute('required')
  expect(await definition()).not.toHaveProperty('defaultAttestationDelegate')
  const address = '0x52908400098527886e0f7030069857d2e4169ee7'
  await delegate.fill(address)
  await advanced.click()
  await expect(delegate).toHaveValue(address)
  const custom = await definition()
  expect(custom.defaultAttestationDelegate).toBe('0x52908400098527886E0F7030069857D2E4169EE7')
  expect(custom.rangeBoundaries).toEqual([-3, -1, 1, 3])
  const preview = await request.post('/api/preview', { data: { market: custom, coefficients: [0, 1], positions: 100 } })
  expect(preview.status()).toBe(200)
  expect((await preview.json()).market).toEqual(custom)
  await simple.click()
  await expect(delegate).toHaveValue(address)
  expect((await definition()).defaultAttestationDelegate).toBe(custom.defaultAttestationDelegate)
  await delegate.fill('0x1234')
  await expect(delegate).toHaveValue('0x1234')
  await expect(page.locator('form').getByRole('alert')).toBeVisible()
  await expect(download).toBeDisabled()
  await expect(create).toBeDisabled()
  await advanced.click()
  await expect(delegate).toHaveValue('0x1234')
  await expect(download).toBeDisabled()
  await expect(create).toBeDisabled()
  await delegate.fill('0x0000000000000000000000000000000000000000')
  await expect(download).toBeEnabled()
  await expect(create).toBeEnabled()
  expect(await definition()).not.toHaveProperty('defaultAttestationDelegate')
  await delegate.fill('')
  await expect(download).toBeEnabled()
  await expect(create).toBeEnabled()
  expect(await definition()).not.toHaveProperty('defaultAttestationDelegate')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})


test('range axis links fields and supports pointer and keyboard boundary editing', async ({ page }) => {
  await openDefinition(page)
  await page.getByRole('button', { name: 'Advanced', exact: true }).click()
  const diagram = page.getByRole('figure', { name: 'Range visualization' })
  const field = page.getByLabel('Range 2 upper (%)', { exact: true })
  await field.focus()
  await expect(diagram.locator('figcaption')).toContainText('Edge between ranges 2 and 3')
  const handle = diagram.getByRole('slider', { name: 'Boundary 2', exact: true })
  await handle.focus()
  await page.keyboard.press('ArrowRight')
  await expect(field).toHaveValue('-0.99')
  await page.keyboard.press('Shift+ArrowRight')
  await expect(field).toHaveValue('0.01')
  await page.keyboard.press('Shift+ArrowRight')
  await expect(field).toHaveValue('1.01')
  await expect(page.getByLabel('Range 3 upper (%)', { exact: true })).toHaveValue('2.005')
  await field.fill('0.01')
  await handle.focus()
  const box = (await handle.boundingBox())!
  await page.mouse.move(box.x + box.width / 2, box.y + 20)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width / 2 + 12, box.y + 20, { steps: 5 })
  await page.mouse.up()
  expect(Number(await field.inputValue())).toBeGreaterThan(.01)
  expect(Number(await field.inputValue())).toBeLessThan(3)
  await expect(handle).toHaveAttribute('aria-valuenow', await field.inputValue())
  await diagram.getByRole('button', { name: /^Range 2:/ }).focus()
  await expect(page.locator('.range-card[data-highlighted="true"]')).toHaveCount(1)
  await expect(page.locator('.range-card[data-tier-id="2"]')).toHaveAttribute('data-highlighted', 'true')
  const edited = await field.inputValue()
  await page.getByRole('button', { name: 'Simple', exact: true }).click()
  await expect(page.getByLabel('Range width (%)', { exact: true })).toHaveValue('2')
  await page.getByRole('button', { name: 'Advanced', exact: true }).click()
  await expect(field).toHaveValue(edited)
  await field.fill('')
  await expect(handle).toHaveAttribute('aria-disabled', 'true')
  await expect(diagram.getByText('Last valid ranges', { exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})


