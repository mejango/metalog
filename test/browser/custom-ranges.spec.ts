test('edits refill unfixed ranges and conflicting fixed boundaries have immediate visual errors', async ({ page }) => {
  await openDefinition(page)
  await page.getByRole('button', { name: 'Advanced', exact: true }).click()
  const boundary = (index: number) => page.getByLabel(`Range ${index} upper (%)`, { exact: true })
  const diagram = page.getByRole('figure', { name: 'Range visualization' })
  await boundary(2).fill('2')
  await expect(boundary(3)).toHaveValue('2.5')
  await expect(page.getByRole('checkbox', { name: 'Fix range 2 upper edge', exact: true })).toBeChecked()
  await boundary(3).fill('2.8')
  await boundary(2).fill('2.9')
  await expect(boundary(2)).toHaveAttribute('aria-invalid', 'true')
  await expect(boundary(3)).toHaveAttribute('aria-invalid', 'true')
  await expect(page.locator('#range-2-upper-error')).toContainText('Edge between ranges 3 and 4')
  await expect(diagram.locator('.range-invalid-marker')).toHaveCount(2)
  await expect(diagram.locator('rect[data-invalid="true"]')).not.toHaveCount(0)
  await expect(page.locator('.range-alert')).toContainText('last valid ranges')
  await expect(page.getByRole('button', { name: 'Download definition', exact: true })).toBeDisabled()
  await expect(diagram.getByRole('slider', { name: 'Boundary 2', exact: true })).toHaveAttribute('aria-disabled', 'true')
  await boundary(2).fill('1')
  await expect(boundary(3)).toHaveValue('2.8')
  await expect(boundary(2)).toHaveAttribute('aria-invalid', 'false')
  await expect(diagram.locator('.range-invalid-marker')).toHaveCount(0)
  await page.getByRole('checkbox', { name: 'Fix range 3 upper edge', exact: true }).uncheck()
  await expect(boundary(3)).toHaveValue('2')
  await expect(page.getByRole('button', { name: 'Download definition', exact: true })).toBeEnabled()
  await page.getByRole('checkbox', { name: 'Fix range 3 upper edge', exact: true }).check()
  await boundary(2).fill('2.9')
  await expect(boundary(2)).toHaveAttribute('aria-invalid', 'true')
  await page.getByRole('checkbox', { name: 'Fix range 3 upper edge', exact: true }).uncheck()
  await expect(boundary(2)).toHaveValue('2.9')
  await expect(boundary(3)).toHaveValue('2.95')
  await expect(boundary(2)).toHaveAttribute('aria-invalid', 'false')
  await boundary(2).fill('-')
  await expect(page.locator('#range-2-upper-error')).toContainText('complete percentage')
  await expect(boundary(2)).toHaveCSS('border-top-color', 'rgb(167, 40, 40)')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})

test('chart selection identifies one range card and neighboring edge editors share a single cutoff', async ({ page }) => {
  await openDefinition(page)
  await page.getByLabel('Ranges', { exact: true }).fill('21')
  await page.getByLabel('Range width (%)', { exact: true }).fill('1')
  await page.getByRole('button', { name: 'Advanced', exact: true }).click()
  const diagram = page.getByRole('figure', { name: 'Range visualization' })
  const selected = page.locator('.range-card[data-highlighted="true"]')
  const card = (tier: number) => page.locator(`.range-card[data-tier-id="${tier}"]`)
  await diagram.getByRole('button', { name: /^Range 5:/ }).focus()
  await expect(page.locator('.range-card')).toHaveCount(21)
  await expect(selected).toHaveCount(1)
  await expect(card(5)).toHaveAttribute('data-highlighted', 'true')
  await expect(card(4)).toHaveAttribute('data-highlighted', 'false')

  const upper = page.getByLabel('Range 4 upper (%)', { exact: true })
  const lower = page.getByLabel('Range 5 lower (%)', { exact: true })
  const upperFixed = page.getByRole('checkbox', { name: 'Fix range 4 upper edge', exact: true })
  const lowerFixed = page.getByRole('checkbox', { name: 'Fix range 5 lower edge', exact: true })
  await upper.fill('-6')
  await expect(lower).toHaveValue('-6')
  await expect(upperFixed).toBeChecked()
  await expect(lowerFixed).toBeChecked()
  await lower.focus()
  await expect(selected).toHaveCount(1)
  await expect(card(5)).toHaveAttribute('data-highlighted', 'true')
  await expect(diagram.locator('figcaption')).toContainText('Edge between ranges 4 and 5')

  const event = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download definition', exact: true }).click()
  const download = await event
  const definition = JSON.parse(await readFile((await download.path())!, 'utf8'))
  expect(definition.rangeBoundaries).toHaveLength(20)
  expect(definition.rangeBoundaries[3]).toBe(-6)
  expect(new Set(definition.rangeBoundaries).size).toBe(20)
  await expect(page.locator('.range-card input[data-edge="upper"]')).toHaveCount(20)
  await expect(page.getByRole('button', { name: /^Remove boundary \d+$/ })).toHaveCount(20)

  await lowerFixed.uncheck()
  await expect(upperFixed).not.toBeChecked()
  await expect(lowerFixed).not.toBeChecked()
  await expect(lower).toHaveValue(await upper.inputValue())
  await lower.fill('-6.25')
  await expect(upper).toHaveValue('-6.25')
  await expect(upperFixed).toBeChecked()
  await expect(lowerFixed).toBeChecked()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})
